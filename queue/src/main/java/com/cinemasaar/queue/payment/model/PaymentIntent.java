package com.cinemasaar.queue.payment.model;

import java.math.BigDecimal;
import java.time.Instant;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.mapping.Document;

@Document(collection = "payment_intents")
@CompoundIndex(name = "uq_booking", def = "{'bookingId': 1}", unique = true)
public class PaymentIntent {

    @Id
    private String id;
    private String bookingId;
    private String userId;
    private BigDecimal amount;
    private PaymentStatus status;
    private String method;
    private String reference;
    private String failureReason;
    private String idempotencyKey;
    private int attempts;
    private Instant createdAt;
    private Instant paidAt;
    private Instant updatedAt;

    public PaymentIntent() {
    }

    public static PaymentIntent pending(String id, String bookingId, String userId,
                                        BigDecimal amount, Instant now) {
        PaymentIntent intent = new PaymentIntent();
        intent.id = id;
        intent.bookingId = bookingId;
        intent.userId = userId;
        intent.amount = amount;
        intent.status = PaymentStatus.PENDING;
        intent.createdAt = now;
        intent.updatedAt = now;
        return intent;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getBookingId() {
        return bookingId;
    }

    public void setBookingId(String bookingId) {
        this.bookingId = bookingId;
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public PaymentStatus getStatus() {
        return status;
    }

    public void setStatus(PaymentStatus status) {
        this.status = status;
    }

    public String getMethod() {
        return method;
    }

    public void setMethod(String method) {
        this.method = method;
    }

    public String getReference() {
        return reference;
    }

    public void setReference(String reference) {
        this.reference = reference;
    }

    public String getFailureReason() {
        return failureReason;
    }

    public void setFailureReason(String failureReason) {
        this.failureReason = failureReason;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(String idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }

    public int getAttempts() {
        return attempts;
    }

    public void setAttempts(int attempts) {
        this.attempts = attempts;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getPaidAt() {
        return paidAt;
    }

    public void setPaidAt(Instant paidAt) {
        this.paidAt = paidAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
